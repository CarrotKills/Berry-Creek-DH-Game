const assert = require("node:assert/strict");
const R = require("./round-state.js");
let state = R.defaultState();
assert.equal(state.version, 8);
assert.deepEqual(state.holeComments, []);
assert.equal(state.settings.photoEmail, "");
state = R.applyAction(state, { type: "SET_PHOTO_EMAIL", payload: { email: " Photos@Example.com " }, meta: { actor: "Admin" } });
assert.equal(state.settings.photoEmail, "photos@example.com");
const photoEmailRevision = state.revision;
state = R.applyAction(state, { type: "SET_PHOTO_EMAIL", payload: { email: "not-an-email" } });
assert.equal(state.settings.photoEmail, "photos@example.com");
assert.equal(state.revision, photoEmailRevision);
for (let i = 0; i < 5; i += 1) state = R.applyAction(state, { type: "ADD_PLAYER", payload: { player: { id: `a${i}`, name: `A${i}`, group: "A" } } });
state = R.applyAction(state, { type: "ADD_PLAYER", payload: { player: { id: "overflow", name: "Overflow", group: "A" } } });
assert.equal(state.players.length, 5);
state = R.applyAction(state, { type: "ADD_PLAYER", payload: { player: { id: "b1", directoryId: "saved-b1", name: "B1", group: "B", teeKey: "member" } } });
assert.equal(state.players.find((p) => p.id === "b1").directoryId, "saved-b1");
state = R.applyAction(state, { type: "SET_SCOREKEEPER", payload: { group: "B", playerId: "b1" } });
assert.equal(state.settings.scorekeepers.B, "b1");
state = R.applyAction(state, { type: "ADD_HOLE_COMMENT", payload: { comment: { id: "comment-1", hole: 4, text: "Pin is back right.", authorAccountId: "account-b1", authorName: "B1", authorGroup: "B", createdAt: "2026-10-10T14:00:00.000Z" } } });
assert.equal(state.holeComments.length, 1);
assert.equal(state.holeComments[0].hole, 4);
assert.equal(state.holeComments[0].authorGroup, "B");
const commentRevision = state.revision;
state = R.applyAction(state, { type: "ADD_HOLE_COMMENT", payload: { comment: { id: "comment-1", hole: 4, text: "Duplicate", authorName: "B1" } } });
assert.equal(state.revision, commentRevision);
assert.equal(state.holeComments[0].text, "Pin is back right.");
state = R.applyAction(state, { type: "DELETE_HOLE_COMMENT", payload: { commentId: "comment-1", hole: 4 } });
assert.deepEqual(state.holeComments, []);
state = R.applyAction(state, { type: "ADD_HOLE_COMMENT", payload: { comment: { id: "comment-2", hole: 8, text: "Wind into us.", authorAccountId: "account-b1", authorName: "B1", authorGroup: "B", createdAt: "2026-10-10T14:05:00.000Z" } } });
const uniqueRosterRevision = state.revision;
state = R.applyAction(state, { type: "ADD_PLAYER", payload: { player: { id: "duplicate-b1", directoryId: "saved-b1", name: "B1 duplicate", group: "C" } } });
assert.equal(state.players.some((p) => p.id === "duplicate-b1"), false);
assert.equal(state.revision, uniqueRosterRevision);
state = R.applyAction(state, { type: "ADD_PLAYER", payload: { player: { id: "b1", name: "Duplicate ID", group: "D" } } });
assert.equal(state.players.filter((p) => p.id === "b1").length, 1);
assert.equal(state.revision, uniqueRosterRevision);
state = R.applyAction(state, { type: "UPDATE_PLAYER", payload: { playerId: "a0", directoryId: "saved-b1" } });
assert.equal(state.players.find((p) => p.id === "a0").directoryId, "");
assert.equal(state.revision, uniqueRosterRevision);
const normalizedUniqueRoster = R.normalizeState({ players: [
  { id: "saved-first", directoryId: "same-saved-player", name: "Saved Player", group: "A" },
  { id: "saved-second", directoryId: "same-saved-player", name: "Saved Player duplicate", group: "B" }
] });
assert.equal(normalizedUniqueRoster.players.length, 1);
assert.equal(normalizedUniqueRoster.players[0].id, "saved-first");
state = R.applyAction(state, { type: "UPDATE_PLAYER", payload: { playerId: "b1", ghin: 8.6, directoryId: "saved-b1" } });
assert.equal(state.players.find((p) => p.id === "b1").ghin, 8.6);
state = R.applyAction(state, { type: "UPDATE_PLAYER", payload: { playerId: "b1", group: "C" } });
assert.equal(state.settings.scorekeepers.B, undefined);
state = R.applyAction(state, { type: "UPDATE_PLAYER", payload: { playerId: "b1", group: "B" } });
state = R.applyAction(state, { type: "SET_SCOREKEEPER", payload: { group: "B", playerId: "b1" } });
state = R.applyAction(state, { type: "SET_SCORE", payload: { playerId: "b1", holeIndex: 0, score: 4 } });
assert.equal(state.players.find((p) => p.id === "b1").scores[0], 4);
assert.equal(state.undoStack.at(-1).group, "B");
assert.equal(state.groupActivity.B.action, "SET_SCORE");
state = R.applyAction(state, { type: "UNDO_LAST", payload: { group: "B" } });
assert.equal(state.players.find((p) => p.id === "b1").scores[0], "");
assert.match(state.auditLog.at(-1).detail, /Undid/);
state = R.applyAction(state, { type: "SET_SCORE", payload: { playerId: "b1", holeIndex: 0, score: 4 } });
state = R.applyAction(state, { type: "SET_SANDY", payload: { playerId: "b1", holeIndex: 0, value: true } });
assert.equal(state.players.find((p) => p.id === "b1").sandies[0], true);
state = R.applyAction(state, { type: "SET_SCORE", payload: { playerId: "b1", holeIndex: 0, score: 5 } });
assert.equal(state.players.find((p) => p.id === "b1").sandies[0], false);
state = R.applyAction(state, { type: "UNDO_LAST", payload: { group: "B" } });
assert.equal(state.players.find((p) => p.id === "b1").scores[0], 4);
assert.equal(state.players.find((p) => p.id === "b1").sandies[0], true);
state = R.applyAction(state, { type: "SET_SCORE", payload: { playerId: "b1", holeIndex: 0, score: 5 } });
state = R.applyAction(state, { type: "SET_SANDY", payload: { playerId: "b1", holeIndex: 0, value: true } });
assert.equal(state.players.find((p) => p.id === "b1").sandies[0], false);
state = R.applyAction(state, { type: "SET_SCORE", payload: { playerId: "b1", holeIndex: 1, score: 3 } });
state = R.applyAction(state, { type: "SET_SANDY", payload: { playerId: "b1", holeIndex: 1, value: true } });
const sandyParThreeRevision = state.revision;
state = R.applyAction(state, { type: "SET_KP", payload: { hole: 2, playerId: "b1", value: true } });
assert.equal(state.revision, sandyParThreeRevision);
assert.equal(state.settings.kpWinners["2"], undefined);
state = R.applyAction(state, { type: "SET_SANDY", payload: { playerId: "b1", holeIndex: 1, value: false } });
state = R.applyAction(state, { type: "SET_KP", payload: { hole: 2, playerId: "b1", value: true } });
assert.equal(state.settings.kpWinners["2"], "b1");
assert.deepEqual(state.settings.kpClaims["2"], ["b1"]);
const kpParThreeRevision = state.revision;
state = R.applyAction(state, { type: "SET_SANDY", payload: { playerId: "b1", holeIndex: 1, value: true } });
assert.equal(state.revision, kpParThreeRevision);
assert.equal(state.players.find((player) => player.id === "b1").sandies[1], false);
state = R.applyAction(state, { type: "SET_SCORE", payload: { playerId: "b1", holeIndex: 3, score: 4 } });
const noBunkerHoleFourRevision = state.revision;
state = R.applyAction(state, { type: "SET_SANDY", payload: { playerId: "b1", holeIndex: 3, value: true } });
assert.equal(state.revision, noBunkerHoleFourRevision);
assert.equal(state.players.find((player) => player.id === "b1").sandies[3], false);
state = R.applyAction(state, { type: "SET_SCORE", payload: { playerId: "b1", holeIndex: 11, score: 3 } });
const noBunkerHoleTwelveRevision = state.revision;
state = R.applyAction(state, { type: "SET_SANDY", payload: { playerId: "b1", holeIndex: 11, value: true } });
assert.equal(state.revision, noBunkerHoleTwelveRevision);
assert.equal(state.players.find((player) => player.id === "b1").sandies[11], false);
const normalizedNoBunkerSandies = R.normalizePlayer({ id: "no-bunker", scores: Array(18).fill(4), sandies: Array(18).fill(true) });
assert.equal(normalizedNoBunkerSandies.sandies[3], false);
assert.equal(normalizedNoBunkerSandies.sandies[11], false);
state = R.applyAction(state, { type: "SET_KP", payload: { hole: 2, playerId: "a1", value: true } });
assert.equal(state.settings.kpWinners["2"], "a1");
assert.notEqual(state.settings.kpWinners["2"], "b1");
assert.deepEqual(state.settings.kpClaims["2"], ["b1", "a1"]);
state = R.applyAction(state, { type: "SET_KP", payload: { hole: 2, playerId: "a2", value: true } });
assert.equal(state.settings.kpWinners["2"], "a2");
assert.deepEqual(state.settings.kpClaims["2"], ["b1", "a2"], "A corrected KP replaces the earlier Group A claim only");
state = R.applyAction(state, { type: "SET_KP", payload: { hole: 2, playerId: "a2", value: false } });
assert.equal(state.settings.kpWinners["2"], "b1");
assert.deepEqual(state.settings.kpClaims["2"], ["b1"], "Removing the latest claim restores the prior group's claim");
state = R.applyAction(state, { type: "SET_KP", payload: { hole: 2, playerId: "a1", value: true } });
state = R.applyAction(state, { type: "UNDO_LAST", payload: { group: "A" } });
assert.equal(state.settings.kpWinners["2"], "b1");
assert.deepEqual(state.settings.kpClaims["2"], ["b1"]);
const migrated = R.normalizeState({ players: state.players, settings: { kpWinners: { 2: "b1" } } });
assert.deepEqual(migrated.settings.kpClaims["2"], ["b1"]);
state = R.applyAction(state, { type: "SET_KP", payload: { hole: 2, playerId: "" } });
assert.equal(state.settings.kpWinners["2"], undefined);
assert.equal(state.settings.kpClaims["2"], undefined);
const playerCount = state.players.length;
state = R.applyAction(state, { type: "RESET_SCORES" });
assert.equal(state.players.length, playerCount);
assert.equal(state.players.find((p) => p.id === "b1").scores.every((score) => score === ""), true);
assert.deepEqual(state.settings.kpWinners, {});
assert.deepEqual(state.settings.kpClaims, {});
assert.deepEqual(state.holeComments, []);
assert.equal(state.settings.photoEmail, "photos@example.com", "Resetting scores keeps the shared photo email");
assert.equal(state.settings.scorekeepers.B, "b1", "Resetting scores keeps the group scorekeeper");
assert.deepEqual(state.undoStack, []);
assert.deepEqual(state.groupActivity, {});
assert.equal(state.auditLog.length > 0, true);
assert.match(state.auditLog.at(-1).detail, /Reset all scores/);
state = R.applyAction(state, { type: "SET_LOCKED", payload: { locked: true }, meta: { actor: "Admin", at: "2026-09-01T12:00:00.000Z" } });
assert.equal(state.settings.locked, true);
assert.equal(state.auditLog.at(-1).actor, "Admin");
state = R.applyAction(state, { type: "SET_LOCKED", payload: { locked: false } });
assert.equal(state.settings.locked, false);
state = R.applyAction(state, { type: "CLEAR_AUDIT" });
assert.equal(state.auditLog.length, 1);
assert.match(state.auditLog[0].detail, /Cleared change history/);
const oldRoundId = state.roundId;
state = R.applyAction(state, { type: "CLEAR_ROUND" });
assert.notEqual(state.roundId, oldRoundId);
assert.equal(state.players.length, 0);
assert.equal(state.settings.photoEmail, "photos@example.com", "Starting a new event keeps the shared photo email");
const roster = R.defaultState();
roster.players = [R.normalizePlayer({ id: "fresh", name: "Fresh Player", group: "C", scores: Array(18).fill(4), sandies: Array(18).fill(true) })];
state = R.applyAction(state, { type: "START_FROM_SAVED", payload: { state: roster } });
assert.equal(state.players[0].group, "C");
assert.equal(state.players[0].scores.every((score) => score === ""), true);
assert.equal(state.players[0].sandies.every((value) => value === false), true);
assert.deepEqual(state.settings.kpWinners, {});
assert.deepEqual(state.settings.kpClaims, {});
assert.deepEqual(state.settings.scorekeepers, {});
assert.equal(state.settings.photoEmail, "photos@example.com", "Reusing a saved roster keeps the current shared photo email");
let eligibilityState = R.defaultState();
eligibilityState = R.applyAction(eligibilityState, { type: "ADD_PLAYER", payload: { player: { id: "eligible", name: "Same Guest", isGuest: true, inGame: true, group: "A" } } });
eligibilityState = R.applyAction(eligibilityState, { type: "ADD_PLAYER", payload: { player: { id: "score-only", name: "Same Guest", isGuest: true, inGame: false, group: "B" } } });
assert.equal(eligibilityState.players.length, 2);
assert.equal(eligibilityState.players.every((player) => player.isGuest), true);
eligibilityState = R.applyAction(eligibilityState, { type: "SET_SCORE", payload: { playerId: "score-only", holeIndex: 0, score: 4 } });
assert.equal(eligibilityState.players.find((player) => player.id === "score-only").scores[0], 4);
const beforeRejectedKp = eligibilityState.revision;
eligibilityState = R.applyAction(eligibilityState, { type: "SET_KP", payload: { hole: 2, playerId: "score-only" } });
assert.equal(eligibilityState.revision, beforeRejectedKp);
assert.equal(eligibilityState.settings.kpWinners["2"], undefined);
eligibilityState = R.applyAction(eligibilityState, { type: "SET_KP", payload: { hole: 2, playerId: "eligible" } });
assert.equal(eligibilityState.settings.kpWinners["2"], "eligible");
eligibilityState = R.applyAction(eligibilityState, { type: "UPDATE_PLAYER", payload: { playerId: "eligible", inGame: false } });
assert.equal(eligibilityState.settings.kpWinners["2"], undefined);
assert.equal(eligibilityState.settings.kpClaims["2"], undefined);
console.log("All round state tests passed.");
