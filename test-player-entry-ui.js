"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");

const html = fs.readFileSync("index.html", "utf8");
const app = fs.readFileSync("app.js", "utf8");
const css = fs.readFileSync("styles.css", "utf8");

const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map((match) => match[1]);
assert.equal(new Set(ids).size, ids.length, "HTML IDs must remain unique");
assert.match(html, /id="addPlayerBtn"[^>]*aria-controls="savedPlayerEntryPanel"/);
assert.match(html, /id="addGuestBtn"[^>]*aria-controls="guestEntryPanel"/);
assert.match(html, /id="savedPlayerEntryPanel"[^>]*hidden/);
assert.match(html, /id="guestEntryPanel"[^>]*hidden/);
assert.ok(html.indexOf('id="savedPlayerSearch"') < html.indexOf('id="savedPlayerEntryPanel"'), "Search must appear before the Add Player form");
assert.ok(html.indexOf('id="savedPlayerList"') < html.indexOf('id="savedPlayerEntryPanel"'), "Saved roster must appear before the entry forms");
assert.match(app, /openPlayerEntry\("saved"\)/);
assert.match(app, /openPlayerEntry\("guest"\)/);
assert.match(app, /playerEntryMode = "";\s*render\(\);/);
assert.match(html, /id="savedPlayerPlus"[^>]*aria-pressed="false"/);
assert.match(html, /id="savedPlayerGhin"[^>]*required/);
assert.doesNotMatch(html, /id="savedPlayerGhin"[^>]*value="0\.0"/);
assert.match(html, /id="guestPlayerPlus"[^>]*aria-pressed="false"/);
assert.match(html, /class="player-ghin-plus plus-handicap-toggle admin-control"/);
assert.match(app, /class="saved-ghin-plus plus-handicap-toggle"/);
assert.match(app, /function togglePlusHandicapInput\(input, button\)/);
assert.match(app, /function requiredHandicapValue\(value\)/);
assert.doesNotMatch(app, /summary\.invalid/);
assert.doesNotMatch(app, /invalidSheetRows/);
assert.match(app, /togglePlusHandicapInput\(ghinInput, plusHandicap\)/);
assert.match(app, /togglePlusHandicapInput\(ghin, plusHandicap\)/);
assert.match(html, /id="updateIndexesBtn"[^>]*>Update Indexes</);
assert.match(html, /id="indexUpdateStatus"[^>]*aria-live="polite"/);
assert.match(app, /Are you sure you want to update, the roster is outdated\./);
assert.match(app, /\/api\/players\/update-indexes/);
assert.doesNotMatch(html, /id="savedPlayerUsername"/);
assert.doesNotMatch(html, /id="savedPlayerPin"/);
assert.doesNotMatch(html, /id="guestPlayerUsername"/);
assert.doesNotMatch(html, /id="guestPlayerPin"/);
assert.match(html, /name exactly as it appears in GHIN/);
assert.match(html, /default PIN 1234/);
assert.match(html, /id="playerInviteLinkDialog"/);
assert.match(html, /id="playerInviteDialog"/);
assert.match(html, /id="invitedPlayerUsername"[^>]*readonly/);
assert.match(html, /Username \(first\.last; e\.g\. John\.Smith\)/);
assert.match(app, /\/api\/player-invitations/);
assert.match(app, /\/api\/player-invitations\/preview\?token=/);
assert.match(app, /Create reset link/);
assert.match(app, /Create login link/);
assert.match(app, /function acceptPlayerInvitation\(event\)/);
assert.match(app, /class="admin-linked-player admin-control"/);
assert.match(app, /One login provides both admin and player access\./);
assert.match(app, /currentUser\?\.role === "admin"/);
assert.match(app, /Admin-linked login/);
assert.doesNotMatch(app, /player-login-status/);
assert.doesNotMatch(css, /player-login-status/);
assert.doesNotMatch(html, /id="bootstrapAdminUsername"/);
assert.doesNotMatch(html, /id="invitedAdminUsername"/);
assert.doesNotMatch(app, /admin-account-username/);
assert.match(app, /Name \(match GHIN\)/);
assert.match(app, /Login: \$\{body\.admin\.username\}/);
assert.match(html, /id="saveRoundBtn"[^>]*>Save round</);
assert.doesNotMatch(html, /Save current round/);
const settingsOrder = ["Device preferences", "Start a new round", "Finalize and lock round", "Save round", "Event readiness", "Live event status", "Historical reference", "Named accountability", "Change history"].map((label) => html.indexOf(label));
assert.equal(settingsOrder.every((position) => position >= 0), true, "Every requested Settings section must be present");
assert.deepEqual(settingsOrder, [...settingsOrder].sort((a, b) => a - b), "Settings sections must follow the requested order");
assert.match(html, />GHIN IDX</);
assert.doesNotMatch(html, />HCP IDX</);
assert.match(app, /<span class="field-label">GHIN IDX<\/span>/);
assert.match(html, /class="saved-tee-field"/);
assert.match(html, /class="guest-tee-field"/);
assert.match(html, /class="player-tee-field"/);
assert.match(app, />\$\{group\} \(\$\{count\}/);
assert.doesNotMatch(html, /id="checkUpdateBtn"/);
assert.doesNotMatch(app, /#checkUpdateBtn/);
assert.match(app, /checkVersion\(\);\s*\}\)\(\);/);

console.log("Player-entry UI tests passed.");
